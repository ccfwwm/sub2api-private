import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount, type VueWrapper } from '@vue/test-utils'
import MediaProtocolManager from '../MediaProtocolManager.vue'

const api = vi.hoisted(() => ({ list: vi.fn(), history: vi.fn(), save: vi.fn(), updateTemplate: vi.fn(), archive: vi.fn(), preview: vi.fn(), test: vi.fn(), detail: vi.fn(), artifactAccess: vi.fn(), mediaPreviewTimeoutMs: vi.fn() }))
const route = vi.hoisted(() => ({ query: {} as Record<string, string> }))
vi.mock('@/api/media-protocols', () => ({ mediaProtocolsAPI: api, mediaPreviewTimeoutMs: api.mediaPreviewTimeoutMs }))
vi.mock('@/api/media', () => ({ mediaAPI: { detail: api.detail, artifactAccess: api.artifactAccess }, MediaTask: {} }))
vi.mock('vue-router', () => ({ useRoute: () => route }))
vi.mock('@/composables/useStepUp', () => ({ useStepUp: () => ({ run: (fn: () => Promise<void>) => fn() }), isStepUpCancelled: () => false }))
const options = { global: { stubs: { TotpStepUpDialog: true, RouterLink: true } } }
async function click(wrapper: VueWrapper, label: string) {
  const button = wrapper.findAll('button').find(candidate => candidate.text() === label)
  expect(button, label).toBeDefined(); await button!.trigger('click'); await flushPromises()
}
const row = () => ({ id: 'video-template', version: 3, published_version: 3, status: 'enabled', config: { id: 'video-template', name: '原协议', description: '原介绍', version: '3', schema_version: 1, media_types: ['video'], operations: ['video'], mode: 'async', poll_seconds: 10, auth: {mode:'bearer'}, submit:{method:'POST',path:'/v1/videos',encoding:'json'} } })
beforeEach(() => {
  vi.resetAllMocks(); route.query = {}; api.list.mockResolvedValue([])
  api.mediaPreviewTimeoutMs.mockImplementation((body: Record<string, unknown>) => 30000 + Math.ceil(new TextEncoder().encode(JSON.stringify(body)).byteLength / (128 * 1024)) * 1000)
  api.updateTemplate.mockImplementation(async body => ({ id: body.id, version: 1, published_version: 1, status: 'enabled', config: body.config }))
})
describe('simple protocol template management', () => {
  it('creates and edits title and introduction through the form, then saves directly', async () => {
    const wrapper = mount(MediaProtocolManager, options); await flushPromises(); await click(wrapper, '新建')
    const title = wrapper.get('[aria-label="模板名称"]'), titleInput = title.element as HTMLInputElement
    titleInput.value = '自x定义协议'; titleInput.setSelectionRange(2, 2)
    await title.trigger('input'); await flushPromises()
    expect(titleInput.selectionStart).toBe(2)
    await wrapper.get('[aria-label="模板名称"]').setValue('自建视频协议')
    await wrapper.get('[aria-label="模板介绍"]').setValue('支持多个图片、视频和音频')
    await click(wrapper, '保存模板')
    expect(api.updateTemplate).toHaveBeenCalledWith(expect.objectContaining({ expected_version: 0, config: expect.objectContaining({name:'自建视频协议',description:'支持多个图片、视频和音频',poll_seconds:10}) }))
    expect(api.history).not.toHaveBeenCalled(); expect(api.save).not.toHaveBeenCalled()
    expect(wrapper.text()).toContain('已保存'); expect(wrapper.find('[role="alert"]').exists()).toBe(false)
    expect(wrapper.text()).not.toContain('草稿 v'); expect(wrapper.text()).not.toContain('历史、')
    wrapper.unmount()
  })
  it('loads the current configuration, copies to a distinct editable template and preserves the source', async () => {
    const source = row(); api.list.mockImplementation(async kind => kind === 'templates' ? [source] : [])
    const wrapper = mount(MediaProtocolManager, options); await flushPromises(); await wrapper.get('aside button').trigger('click'); await flushPromises()
    await wrapper.get('[aria-label="模板名称"]').setValue('改过的标题')
    await click(wrapper, '保存模板')
    expect(api.updateTemplate.mock.calls[0][0]).toMatchObject({id:source.id,expected_version:3,expected_config:source.config,config:{name:'改过的标题'}})
    await click(wrapper, '复制模板'); await click(wrapper, '保存模板')
    const copied=api.updateTemplate.mock.calls[1][0]
    expect(copied.expected_version).toBe(0); expect(copied.id).not.toBe(source.id); expect(copied.config.name).toContain('副本')
    expect(source.config.name).toBe('原协议'); wrapper.unmount()
  })
  it('deletes only after inline confirmation and shows backend conflicts', async () => {
    const source=row(); api.list.mockImplementation(async kind=>kind==='templates'?[source]:[])
    const wrapper=mount(MediaProtocolManager,options); await flushPromises(); await wrapper.get('aside button').trigger('click'); await flushPromises()
    await click(wrapper,'删除模板'); expect(api.updateTemplate).not.toHaveBeenCalled()
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('停用')
    api.updateTemplate.mockRejectedValueOnce(new Error('模板已被修改，请刷新后重试'))
    await click(wrapper,'确认删除'); expect(wrapper.get('[role="alert"]').text()).toContain('模板已被修改')
    api.updateTemplate.mockResolvedValueOnce({}); api.list.mockResolvedValue([])
    await click(wrapper,'确认删除'); expect(api.updateTemplate).toHaveBeenLastCalledWith({id:source.id,expected_version:3,expected_config:source.config,delete:true})
    expect(wrapper.text()).toContain('已删除'); wrapper.unmount()
  })
  it('retains account-scoped bindings when the template list fails', async()=>{
    route.query={tab:'bindings',account_id:'2139',group_id:'19'}
    api.list.mockImplementation(async kind=>{if(kind==='templates')throw Error('Template list unavailable');return [{id:'desired',config:{account_id:2139,group_id:19}},{id:'other-account',config:{account_id:2140,group_id:19}}]})
    const wrapper=mount(MediaProtocolManager,options);await flushPromises()
    expect(wrapper.text()).toContain('desired');expect(wrapper.text()).not.toContain('other-account');expect(wrapper.get('[role="alert"]').text()).toContain('Template list unavailable');wrapper.unmount()
  })
  it('previews with the actual relay key without saving a template',async()=>{
    api.preview.mockResolvedValue({paid_submission:false})
    const wrapper=mount(MediaProtocolManager,options);await flushPromises();await click(wrapper,'新建')
    await wrapper.get('[aria-label="预览 API Key"]').setValue('sk-local-test')
    await wrapper.get('[aria-label="预览候选账号 ID"]').setValue('7')
    await click(wrapper,'预览实际绑定与估价')
    expect(api.preview).toHaveBeenCalledWith(expect.objectContaining({mode:'effective',api_key:'sk-local-test',account_id:7}))
    expect(api.updateTemplate).not.toHaveBeenCalled();wrapper.unmount()
  })
  it('shows free preview upload size, bounded timeout, and safe retry after a timeout',async()=>{
    api.preview.mockRejectedValueOnce(Object.assign(new Error('timeout'),{code:'ECONNABORTED'}))
    const wrapper=mount(MediaProtocolManager,options);await flushPromises();await click(wrapper,'新建')
    await wrapper.findAll('details summary').find(item=>item.text().includes('免费预览、模型发现与付费测试'))!.trigger('click')
    await click(wrapper,'免费预览（不建任务、不扣费）')
    expect(api.mediaPreviewTimeoutMs).toHaveBeenCalled()
    expect(wrapper.text()).toContain('超时上限 31 秒')
    expect(wrapper.text()).toContain('本次没有创建生成任务、没有扣费，可以安全重试')
    expect(api.test).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('requires paid confirmation and displays the durable task phase and billing',async()=>{
    const task={id:'task-91',model:'video-choice',status:'completed',submission_phase:'upstream_accepted',billing:{state:'settled',reserved:'0.25',accepted:'0.25',settled:'0.25',released:'0.00'},data:[{key:'video1',type:'video',mime_type:'video/mp4',size_bytes:1234,duration_seconds:'5',content_url:'/v1/tasks/task-91/artifacts/video1/content',available:true}]}
    api.list.mockImplementation(async kind=>kind==='templates'?[row()]:[])
    api.test.mockResolvedValue(task)
    api.detail.mockResolvedValue({record:{task},incoming_request:{model:'video-choice'},upstream_response:{ok:true}})
    api.artifactAccess.mockResolvedValue({url:'https://example.org/video.mp4',expires_at:9999999999})
    const wrapper=mount(MediaProtocolManager,options);await flushPromises();await wrapper.get('aside button').trigger('click');await flushPromises()
    await wrapper.findAll('details summary').find(item=>item.text().includes('免费预览、模型发现与付费测试'))!.trigger('click')
    await wrapper.get('input[placeholder="输入中转 API Key"]').setValue('sk-local-test')
    const submit=wrapper.findAll('button').find(item=>item.text()==='提交真实生成请求')!
    expect((submit.element as HTMLButtonElement).disabled).toBe(true)
    await wrapper.get('[aria-label="确认本次生成可能收费"]').setValue(true)
    await submit.trigger('click');await flushPromises()
    expect(api.test).toHaveBeenCalledWith(expect.objectContaining({api_key:'sk-local-test',confirm_paid_submission:true}),expect.any(String))
    expect(api.detail).toHaveBeenCalledWith('task-91')
    expect(wrapper.text()).toContain('生成已完成')
    expect(wrapper.text()).toContain('任务 ID：task-91')
    expect(wrapper.text()).toContain('已结算 0.25')
    expect(wrapper.text()).toContain('成品与下载')
    await click(wrapper,'获取成品链接')
    expect(wrapper.get('a[href="https://example.org/video.mp4"]').text()).toContain('打开 / 下载成品')
    const evidence = wrapper.findAll('details').find(item => item.text().includes('完整 JSON / 上下游证据'))
    expect(evidence).toBeDefined()
    expect(evidence!.attributes('open')).toBeUndefined()
    wrapper.unmount()
  })
  it('recovers an ambiguous paid submission with the identical body and idempotency key',async()=>{
    const task={id:'task-recovered',model:'video-choice',status:'queued',submission_phase:'local_pending',billing:{state:'held',reserved:'0.25',accepted:'0.00',settled:'0.00',released:'0.00'},data:[]}
    api.list.mockImplementation(async kind=>kind==='templates'?[row()]:[])
    api.test.mockRejectedValueOnce(Object.assign(new Error('Network Error'),{code:'ERR_NETWORK'})).mockResolvedValueOnce(task)
    api.detail.mockResolvedValue({record:{task},incoming_request:{model:'video-choice'}})
    const wrapper=mount(MediaProtocolManager,options);await flushPromises();await wrapper.get('aside button').trigger('click');await flushPromises()
    await wrapper.findAll('details summary').find(item=>item.text().includes('免费预览、模型发现与付费测试'))!.trigger('click')
    await wrapper.get('input[placeholder="输入中转 API Key"]').setValue('sk-local-test')
    await wrapper.get('[aria-label="确认本次生成可能收费"]').setValue(true)
    await click(wrapper,'提交真实生成请求')
    expect(wrapper.text()).toContain('本站受理结果不明确')
    const firstCall=api.test.mock.calls[0]
    expect(firstCall[0]).toMatchObject({api_key:'sk-local-test',confirm_paid_submission:true})
    expect(typeof firstCall[1]).toBe('string')
    await click(wrapper,'恢复 / 查询原任务')
    expect(api.test).toHaveBeenCalledTimes(2)
    expect(api.test.mock.calls[1][0]).toEqual(firstCall[0])
    expect(api.test.mock.calls[1][1]).toBe(firstCall[1])
    expect(wrapper.text()).toContain('任务 ID：task-recovered')
    wrapper.unmount()
  })
  it('keeps an unknown upstream result on the same task instead of enabling a new paid test',async()=>{
    const task={id:'task-unknown',model:'video-choice',status:'unknown',submission_phase:'reconciling',billing:{state:'manual_review',reserved:'0.25',accepted:'0.00',settled:'0.00',released:'0.00'},data:[]}
    api.list.mockImplementation(async kind=>kind==='templates'?[row()]:[])
    api.test.mockResolvedValue(task)
    api.detail.mockResolvedValue({record:{task},incoming_request:{model:'video-choice'}})
    const wrapper=mount(MediaProtocolManager,options);await flushPromises();await wrapper.get('aside button').trigger('click');await flushPromises()
    await wrapper.findAll('details summary').find(item=>item.text().includes('免费预览、模型发现与付费测试'))!.trigger('click')
    await wrapper.get('input[placeholder="输入中转 API Key"]').setValue('sk-local-test')
    await wrapper.get('[aria-label="确认本次生成可能收费"]').setValue(true)
    await click(wrapper,'提交真实生成请求')
    expect(wrapper.text()).toContain('上游受理结果待核对')
    const newTest=wrapper.findAll('button').find(item=>item.text()==='明确开始另一次测试')!
    expect((newTest.element as HTMLButtonElement).disabled).toBe(true)
    wrapper.unmount()
  })
})
